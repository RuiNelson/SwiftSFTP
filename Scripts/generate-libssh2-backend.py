#!/usr/bin/env python3
"""Prepare libssh2's qualified OpenSSL and directional transport adapters."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Vendor/libssh2/src/openssl.h"
OUTPUT = ROOT / "Sources/libssh2/openssl/openssl_backend.h"
TRANSPORT_SOURCE = ROOT / "Vendor/libssh2/src/transport.c"
TRANSPORT_OUTPUT = ROOT / "Sources/libssh2/transport.c"


def transport_adapter():
    original = TRANSPORT_SOURCE.read_text()
    upstream_check = (
        "        /* Check for and deal with decompression */\n"
        "        compressed = session->local.comp &&\n"
        "                     session->local.comp->compress &&\n"
        "                     ((session->state & SSH2_STATE_AUTHENTICATED) ||\n"
        "                      session->local.comp->use_in_auth);"
    )
    fixed_check = upstream_check.replace("session->local.comp", "session->remote.comp")
    if original.count(upstream_check) == 1:
        adapted = original.replace(upstream_check, fixed_check, 1)
    elif original.count(fixed_check) == 1:
        raise SystemExit(
            "The pinned libssh2 already fixes incoming decompression; drop the transport adapter "
            "and compile Vendor/libssh2/src/transport.c"
        )
    else:
        raise SystemExit("The pinned libssh2 decompression check changed; review the transport adapter")
    return (
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Based on Vendor/libssh2/src/transport.c, with upstream license preserved.\n"
        " * Incoming decompression uses the remote endpoint's negotiated compression.\n"
        " */\n" + adapted
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed adapter is stale")
    args = parser.parse_args()
    original = SOURCE.read_text()
    if "#ifndef LIBSSH2_OPENSSL_H" not in original:
        raise SystemExit("The pinned libssh2 OpenSSL include guard changed; review the adapter")
    adapted, count = re.subn(
        r"(#\s*include\s*)<openssl/([^>]+)>",
        r"\1<SwiftSFTP_OpenSSL/\2>", original
    )
    if not count:
        raise SystemExit("No OpenSSL includes found in the pinned libssh2 backend")
    expected = (
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Only OpenSSL include paths differ from Vendor/libssh2/src/openssl.h.\n"
        " * Loaded through HAVE_CONFIG_H before libssh2 selects its crypto backend.\n"
        " */\n" + adapted
    )
    expected_transport = transport_adapter()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("Stale OpenSSL backend: run python3 Scripts/generate-libssh2-backend.py")
        print(f"PASS: OpenSSL backend matches libssh2, with {count} qualified includes")
        if not TRANSPORT_OUTPUT.is_file() or TRANSPORT_OUTPUT.read_text() != expected_transport:
            raise SystemExit("Stale transport adapter: run python3 Scripts/generate-libssh2-backend.py")
        print("PASS: Transport adapter matches libssh2 with directional decompression")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f"Generated OpenSSL backend with {count} qualified includes")
        TRANSPORT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        TRANSPORT_OUTPUT.write_text(expected_transport)
        print("Generated transport adapter with directional decompression")


if __name__ == "__main__":
    main()
