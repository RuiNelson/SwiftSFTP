#!/usr/bin/env python3
"""Prepare libssh2's qualified OpenSSL, transport and per-handle SFTP read adapters."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "Vendor/libssh2/src/openssl.h"
OUTPUT = ROOT / "Sources/libssh2/openssl/openssl_backend.h"
TRANSPORT_SOURCE = ROOT / "Vendor/libssh2/src/transport.c"
TRANSPORT_OUTPUT = ROOT / "Sources/libssh2/transport.c"
SFTP_SOURCE = ROOT / "Vendor/libssh2/src/sftp.c"
SFTP_OUTPUT = ROOT / "Sources/libssh2/sftp.c"
SFTP_HEADER_SOURCE = ROOT / "Vendor/libssh2/src/sftp.h"
SFTP_HEADER_OUTPUT = ROOT / "Sources/libssh2/sftp.h"


def replace_exactly(text, old, new, count, what):
    if text.count(old) != count:
        raise SystemExit(f"The pinned libssh2 {what} changed; review the libssh2 adapter")
    return text.replace(old, new)


def sftp_adapter():
    """Keep sftp_read()'s resume state per file handle instead of per SFTP session.

    Upstream shares one state for every handle, and libssh2_sftp_seek64() leaves it alone. After a read that returned
    EAGAIN or timed out while waiting for responses, the next read on a handle with nothing in flight (that handle after
    a seek, or another one) skipped sending requests and failed with "sftp_read() internal error".
    """
    original = SFTP_SOURCE.read_text()
    original_header = SFTP_HEADER_SOURCE.read_text()
    if "u.file.read_state" in original or "filep->read_state" in original:
        raise SystemExit(
            "The pinned libssh2 already keeps the SFTP read state per handle; drop the SFTP adapter "
            "and compile Vendor/libssh2/src/sftp.c"
        )

    header = replace_exactly(
        original_header,
        "    /* State variable used in sftp_read() */\n    ssh2_NB_states read_state;\n\n",
        "",
        1,
        "SFTP session read state",
    )
    header = replace_exactly(
        header,
        "            char eof; /* we have read to the end */\n",
        "            char eof; /* we have read to the end */\n\n"
        "            /* State variable used in sftp_read() */\n"
        "            ssh2_NB_states read_state;\n",
        1,
        "SFTP file handle data",
    )

    adapted = replace_exactly(
        original,
        "       what phase of execution we were at.  The state is stored in\n"
        "       sftp->read_state.\n",
        "       what phase of execution we were at.  The state is stored in\n"
        "       handle->u.file.read_state, so that an interrupted read is only\n"
        "       resumed on its own handle.\n",
        1,
        "sftp_read() state comment",
    )
    adapted = replace_exactly(
        adapted,
        "    sftp_packetlist_flush(handle);\n    sftp->read_state = ssh2_NB_state_idle;\n",
        "    sftp_packetlist_flush(handle);\n",
        1,
        "SFTP handle close",
    )
    adapted = replace_exactly(
        adapted,
        "    /* discard all pending requests and currently read data */\n    sftp_packetlist_flush(handle);\n",
        "    /* discard all pending requests and currently read data */\n    sftp_packetlist_flush(handle);\n\n"
        "    /* an interrupted sftp_read() has nothing left to resume */\n"
        "    handle->u.file.read_state = ssh2_NB_state_idle;\n",
        1,
        "SFTP seek",
    )
    adapted = replace_exactly(adapted, "sftp->read_state", "filep->read_state", 5, "sftp_read() state machine")

    return (
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Based on Vendor/libssh2/src/sftp.c, with upstream license preserved.\n"
        " * sftp_read() keeps its resume state per file handle, and a seek resets it.\n"
        " */\n" + adapted,
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Based on Vendor/libssh2/src/sftp.h, with upstream license preserved.\n"
        " * sftp_read()'s resume state moves from the SFTP session to each file handle.\n"
        " */\n" + header,
    )


def transport_adapter():
    original = TRANSPORT_SOURCE.read_text()
    upstream_check = (
        "        /* Check for and deal with decompression */\n"
        "        compressed = session->local.comp &&\n"
        "                     session->local.comp->compress &&\n"
        "                     ((session->state & SSH2_STATE_AUTHENTICATED) ||\n"
        "                      session->local.comp->use_in_auth);"
    )
    fixed_check = upstream_check.replace("session->local.comp", "session->remote.comp")
    if original.count(upstream_check) == 1:
        adapted = original.replace(upstream_check, fixed_check, 1)
    elif original.count(fixed_check) == 1:
        adapted = original
    else:
        raise SystemExit("The pinned libssh2 decompression check changed; review the transport adapter")

    # A fatal socket send cannot finish the pending packet. Keeping it would make every different packet, including
    # the channel close that frees the session, return EAGAIN without ever trying the dead socket.
    adapted = replace_exactly(
        adapted,
        "        if(rc != -EAGAIN)\n"
        "            /* send failure! */\n"
        "            return LIBSSH2_ERROR_SOCKET_SEND;\n",
        "        if(rc != -EAGAIN) {\n"
        "            /* A fatal send cannot resume this packet. Allow local cleanup\n"
        "               to proceed instead of rejecting every later packet. */\n"
        "            p->ototal_num = 0;\n"
        "            p->olen = 0;\n"
        "            return LIBSSH2_ERROR_SOCKET_SEND;\n"
        "        }\n",
        1,
        "transport pending-packet send failure",
    )
    return (
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Based on Vendor/libssh2/src/transport.c, with upstream license preserved.\n"
        " * Incoming decompression uses the remote endpoint's negotiated compression.\n"
        " * A fatal socket send releases the pending packet for local cleanup.\n"
        " */\n" + adapted
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the committed adapter is stale")
    args = parser.parse_args()
    original = SOURCE.read_text()
    if "#ifndef LIBSSH2_OPENSSL_H" not in original:
        raise SystemExit("The pinned libssh2 OpenSSL include guard changed; review the adapter")
    adapted, count = re.subn(
        r"(#\s*include\s*)<openssl/([^>]+)>",
        r"\1<SwiftSFTP_OpenSSL/\2>", original
    )
    if not count:
        raise SystemExit("No OpenSSL includes found in the pinned libssh2 backend")
    expected = (
        "/* Generated by Scripts/generate-libssh2-backend.py. Do not edit.\n"
        " * Only OpenSSL include paths differ from Vendor/libssh2/src/openssl.h.\n"
        " * Loaded through HAVE_CONFIG_H before libssh2 selects its crypto backend.\n"
        " */\n" + adapted
    )
    expected_transport = transport_adapter()
    expected_sftp, expected_sftp_header = sftp_adapter()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
            raise SystemExit("Stale OpenSSL backend: run python3 Scripts/generate-libssh2-backend.py")
        print(f"PASS: OpenSSL backend matches libssh2, with {count} qualified includes")
        if not TRANSPORT_OUTPUT.is_file() or TRANSPORT_OUTPUT.read_text() != expected_transport:
            raise SystemExit("Stale transport adapter: run python3 Scripts/generate-libssh2-backend.py")
        print("PASS: Transport adapter matches libssh2 with directional decompression and fatal-send cleanup")
        if (
            not SFTP_OUTPUT.is_file()
            or SFTP_OUTPUT.read_text() != expected_sftp
            or not SFTP_HEADER_OUTPUT.is_file()
            or SFTP_HEADER_OUTPUT.read_text() != expected_sftp_header
        ):
            raise SystemExit("Stale SFTP adapter: run python3 Scripts/generate-libssh2-backend.py")
        print("PASS: SFTP adapter matches libssh2 with a per-handle read state")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
        print(f"Generated OpenSSL backend with {count} qualified includes")
        TRANSPORT_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        TRANSPORT_OUTPUT.write_text(expected_transport)
        print("Generated transport adapter with directional decompression and fatal-send cleanup")
        SFTP_OUTPUT.write_text(expected_sftp)
        SFTP_HEADER_OUTPUT.write_text(expected_sftp_header)
        print("Generated SFTP adapter with a per-handle read state")


if __name__ == "__main__":
    main()
